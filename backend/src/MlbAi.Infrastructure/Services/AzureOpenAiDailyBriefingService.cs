using System.Net.Http.Json;
using System.Text.Json;
using System.Text.Json.Serialization;
using MlbAi.Application.Models;

namespace MlbAi.Infrastructure.Services;

public sealed class AzureOpenAiDailyBriefingService(
    HttpClient httpClient,
    AzureOpenAiOptions options)
{
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web);

    public bool IsConfigured => options.IsConfigured;

    public async Task<DailyBriefingDto> GenerateAsync(
        IReadOnlyList<MlbGameDto> games,
        MlbStandingsDto standings,
        MlbStatLeadersDto statLeaders,
        DateTimeOffset generatedAtUtc,
        CancellationToken cancellationToken)
    {
        if (!options.IsConfigured)
        {
            throw new InvalidOperationException("Azure OpenAI is not configured.");
        }

        var requestUri = BuildRequestUri(options);
        var requestBody = new
        {
            messages = new object[]
            {
                new
                {
                    role = "system",
                    content = "You are a concise MLB briefing editor. Use only the supplied MLB data. Never invent scores, players, injuries, predictions, or facts. Keep each detail to one sentence."
                },
                new
                {
                    role = "user",
                    content = JsonSerializer.Serialize(BuildGroundingData(games, standings, statLeaders), JsonOptions)
                }
            },
            max_completion_tokens = 700,
            reasoning_effort = "minimal",
            response_format = new
            {
                type = "json_schema",
                json_schema = new
                {
                    name = "mlb_daily_briefing",
                    strict = true,
                    schema = BuildResponseSchema()
                }
            }
        };

        using var request = new HttpRequestMessage(HttpMethod.Post, requestUri)
        {
            Content = JsonContent.Create(requestBody, options: JsonOptions)
        };
        request.Headers.Add("api-key", options.ApiKey);

        using var response = await httpClient.SendAsync(request, cancellationToken);
        var responseContent = await response.Content.ReadAsStringAsync(cancellationToken);

        if (!response.IsSuccessStatusCode)
        {
            var errorDetail = responseContent.Length > 800
                ? responseContent[..800]
                : responseContent;

            throw new HttpRequestException(
                $"Azure OpenAI returned HTTP {(int)response.StatusCode}: {errorDetail}",
                null,
                response.StatusCode);
        }

        var completion = JsonSerializer.Deserialize<ChatCompletionResponse>(responseContent, JsonOptions);
        var jsonContent = completion?.Choices.FirstOrDefault()?.Message.Content;

        if (string.IsNullOrWhiteSpace(jsonContent))
        {
            throw new InvalidOperationException("Azure OpenAI returned an empty briefing.");
        }

        var generated = JsonSerializer.Deserialize<GeneratedBriefing>(jsonContent, JsonOptions)
            ?? throw new InvalidOperationException("Azure OpenAI returned an invalid briefing payload.");

        return new DailyBriefingDto(
            Mode: "azure-openai",
            IsAiGenerated: true,
            Headline: generated.Headline,
            Summary: generated.Summary,
            KeyGames: generated.KeyGames,
            PlayersToWatch: generated.PlayersToWatch,
            DataNotes:
            [
                "The narrative was generated by Azure OpenAI from MLB Stats API data.",
                $"Model deployment: {options.DeploymentName}.",
                "Scores and player statistics should be verified against the source data shown below."
            ],
            GeneratedAtUtc: generatedAtUtc);
    }

    private static Uri BuildRequestUri(AzureOpenAiOptions configuredOptions)
    {
        var endpoint = configuredOptions.Endpoint.TrimEnd('/');
        var deployment = Uri.EscapeDataString(configuredOptions.DeploymentName);
        var apiVersion = Uri.EscapeDataString(configuredOptions.ApiVersion);

        return new Uri($"{endpoint}/openai/deployments/{deployment}/chat/completions?api-version={apiVersion}");
    }

    private static object BuildGroundingData(
        IReadOnlyList<MlbGameDto> games,
        MlbStandingsDto standings,
        MlbStatLeadersDto statLeaders)
    {
        return new
        {
            instructions = new
            {
                headline = "Summarize Taiwan today's MLB board without making predictions.",
                keyGames = "Choose at most three games that have the clearest supplied story.",
                playersToWatch = "Choose at most four players from the supplied statistical leaders."
            },
            games = games.Take(10).Select(game => new
            {
                game.GameTimeUtc,
                game.AwayTeam,
                game.HomeTeam,
                game.Status,
                game.AwayScore,
                game.HomeScore,
                game.AwayRecord,
                game.HomeRecord,
                game.AwayProbablePitcher,
                game.HomeProbablePitcher,
                homeRunHitters = game.HomeRunHitters?.Take(4).Select(player => new
                {
                    player.Name,
                    player.Team,
                    player.HomeRuns,
                    player.SeasonHomeRuns
                })
            }),
            divisionLeaders = standings.Leagues.SelectMany(league =>
                league.Divisions.Select(division => new
                {
                    league.LeagueName,
                    division.DivisionName,
                    leader = division.Teams.FirstOrDefault()
                })),
            wildCards = standings.WildCards.Select(wildCard => new
            {
                wildCard.LeagueName,
                teams = wildCard.Teams.Take(5)
            }),
            statLeaders = statLeaders.Categories.Select(category => new
            {
                category.Label,
                category.Unit,
                leaders = category.Leaders.Take(3)
            })
        };
    }

    private static object BuildResponseSchema()
    {
        var itemSchema = new
        {
            type = "object",
            properties = new
            {
                title = new { type = "string" },
                detail = new { type = "string" }
            },
            required = new[] { "title", "detail" },
            additionalProperties = false
        };

        return new
        {
            type = "object",
            properties = new
            {
                headline = new { type = "string" },
                summary = new { type = "string" },
                keyGames = new
                {
                    type = "array",
                    items = itemSchema,
                    maxItems = 3
                },
                playersToWatch = new
                {
                    type = "array",
                    items = itemSchema,
                    maxItems = 4
                }
            },
            required = new[] { "headline", "summary", "keyGames", "playersToWatch" },
            additionalProperties = false
        };
    }

    private sealed record ChatCompletionResponse(
        IReadOnlyList<ChatCompletionChoice> Choices);

    private sealed record ChatCompletionChoice(
        ChatCompletionMessage Message);

    private sealed record ChatCompletionMessage(
        string Content);

    private sealed record GeneratedBriefing(
        string Headline,
        string Summary,
        IReadOnlyList<DailyBriefingItemDto> KeyGames,
        IReadOnlyList<DailyBriefingItemDto> PlayersToWatch);
}
